-- =====================================================================
-- 13. POLÍTICAS (quién puede hacer qué)
--     Se borran y se vuelven a crear para poder ejecutar el archivo de nuevo.
--     "(select auth.uid())" con paréntesis es más rápido: Postgres lo
--     calcula una vez por consulta y no una vez por fila.
-- =====================================================================

-- Catálogo público: todos leen, solo el admin escribe -------------------
drop policy if exists "categorias: todos leen"   on public.categorias;
drop policy if exists "categorias: admin edita"  on public.categorias;
create policy "categorias: todos leen"  on public.categorias for select to anon, authenticated using (true);
create policy "categorias: admin edita" on public.categorias for all    to authenticated
    using ((select public.es_admin())) with check ((select public.es_admin()));

drop policy if exists "campanas: todos leen"  on public.campanas;
drop policy if exists "campanas: admin edita" on public.campanas;
create policy "campanas: todos leen"  on public.campanas for select to anon, authenticated using (true);
create policy "campanas: admin edita" on public.campanas for all    to authenticated
    using ((select public.es_admin())) with check ((select public.es_admin()));

drop policy if exists "productos: todos leen los activos" on public.productos;
drop policy if exists "productos: admin edita"            on public.productos;
create policy "productos: todos leen los activos" on public.productos for select to anon, authenticated
    using (activo or (select public.es_admin()));
create policy "productos: admin edita" on public.productos for all to authenticated
    using ((select public.es_admin())) with check ((select public.es_admin()));

-- El stock se lee en público, pero SOLO baja mediante la función de compra
-- (etapa 3). Ningún cliente puede hacer "update variantes set stock = 999".
drop policy if exists "variantes: todos leen"  on public.variantes;
drop policy if exists "variantes: admin edita" on public.variantes;
create policy "variantes: todos leen"  on public.variantes for select to anon, authenticated using (true);
create policy "variantes: admin edita" on public.variantes for all    to authenticated
    using ((select public.es_admin())) with check ((select public.es_admin()));

-- Clientes: cada uno ve y edita SU perfil; el admin ve a todos ---------
-- (El perfil se crea solo al registrarse: lo hacemos en la etapa 2.)
drop policy if exists "clientes: ver el propio o admin"    on public.clientes;
drop policy if exists "clientes: editar el propio o admin" on public.clientes;
create policy "clientes: ver el propio o admin" on public.clientes for select to authenticated
    using (id = (select auth.uid()) or (select public.es_admin()));
create policy "clientes: editar el propio o admin" on public.clientes for update to authenticated
    using (id = (select auth.uid()) or (select public.es_admin()))
    with check (id = (select auth.uid()) or (select public.es_admin()));

-- Cupones: los activos se pueden leer (ya los publicas en la tienda) -----
drop policy if exists "cupones: todos leen los activos" on public.cupones;
drop policy if exists "cupones: admin edita"            on public.cupones;
create policy "cupones: todos leen los activos" on public.cupones for select to anon, authenticated
    using (activo or (select public.es_admin()));
create policy "cupones: admin edita" on public.cupones for all to authenticated
    using ((select public.es_admin())) with check ((select public.es_admin()));

-- Pedidos: el cliente ve los suyos; el admin ve todos y cambia el estado.
-- NO hay política de INSERT a propósito: los pedidos se crean solo con la
-- función de compra de la etapa 3, que recalcula precios en el servidor
-- (si no, alguien podría crear un pedido de S/ 0.01 desde la consola).
drop policy if exists "pedidos: ver los propios o admin" on public.pedidos;
drop policy if exists "pedidos: admin edita"             on public.pedidos;
create policy "pedidos: ver los propios o admin" on public.pedidos for select to authenticated
    using (cliente_id = (select auth.uid()) or (select public.es_admin()));
create policy "pedidos: admin edita" on public.pedidos for update to authenticated
    using ((select public.es_admin())) with check ((select public.es_admin()));

drop policy if exists "items: ver los de mis pedidos o admin" on public.pedido_items;
create policy "items: ver los de mis pedidos o admin" on public.pedido_items for select to authenticated
    using (
        (select public.es_admin())
        or exists (select 1 from public.pedidos p
                   where p.id = pedido_id and p.cliente_id = (select auth.uid()))
    );

-- Reseñas: todos leen; cliente con sesión publica y borra las suyas ------
drop policy if exists "resenas: todos leen"            on public.resenas;
drop policy if exists "resenas: cliente publica"       on public.resenas;
drop policy if exists "resenas: borrar propia o admin" on public.resenas;
create policy "resenas: todos leen" on public.resenas for select to anon, authenticated using (true);
create policy "resenas: cliente publica" on public.resenas for insert to authenticated
    with check (cliente_id = (select auth.uid()));
create policy "resenas: borrar propia o admin" on public.resenas for delete to authenticated
    using (cliente_id = (select auth.uid()) or (select public.es_admin()));

-- Favoritos: cada cliente maneja solo los suyos --------------------------
drop policy if exists "favoritos: solo los propios" on public.favoritos;
create policy "favoritos: solo los propios" on public.favoritos for all to authenticated
    using (cliente_id = (select auth.uid())) with check (cliente_id = (select auth.uid()));

-- Eventos: cualquiera registra una vista; solo el admin los lee ----------
drop policy if exists "eventos: todos registran" on public.eventos_producto;
drop policy if exists "eventos: admin lee"       on public.eventos_producto;
create policy "eventos: todos registran" on public.eventos_producto for insert to anon, authenticated
    with check (cliente_id is null or cliente_id = (select auth.uid()));
create policy "eventos: admin lee" on public.eventos_producto for select to authenticated
    using ((select public.es_admin()));

-- Reclamaciones: cualquiera registra una hoja; solo el admin lee/responde
drop policy if exists "reclamos: todos registran"        on public.reclamaciones;
drop policy if exists "reclamos: admin lee y responde"   on public.reclamaciones;
drop policy if exists "reclamos: admin actualiza"        on public.reclamaciones;
create policy "reclamos: todos registran" on public.reclamaciones for insert to anon, authenticated
    with check (estado = 'Pendiente' and respuesta = ''
                and (cliente_id is null or cliente_id = (select auth.uid())));
create policy "reclamos: admin lee y responde" on public.reclamaciones for select to authenticated
    using ((select public.es_admin()));
create policy "reclamos: admin actualiza" on public.reclamaciones for update to authenticated
    using ((select public.es_admin())) with check ((select public.es_admin()));


