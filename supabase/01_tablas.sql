--  IDEA CLAVE (RLS = Row Level Security = seguridad por fila)
--  Tu llave "publishable" va dentro del JavaScript, o sea que CUALQUIERA
--  puede verla. Eso está bien SOLO si cada tabla tiene RLS activado:
--  con RLS, Postgres revisa cada fila y solo deja leer/escribir lo que
--  dicen las "policies" (políticas) de abajo. Tabla sin políticas = nadie
--  puede tocarla desde el navegador.
--
