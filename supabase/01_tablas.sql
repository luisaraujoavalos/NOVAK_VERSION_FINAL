-- ---------------------------------------------------------------------
-- 1. CATEGORÍAS  (polos, camisas, hoodies...)
-- ---------------------------------------------------------------------
create table if not exists public.categorias (
    id        text primary key,                       -- 'polos'
    nombre    text not null,                          -- 'Polos'
    segmento  text not null check (segmento in ('ropa', 'calzado', 'accesorios')),
    portada   text not null default '',               -- 'img/polos-04.jpg'
    orden     int  not null default 0                 -- orden en el menú
);


-- ---------------------------------------------------------------------
-- 2. CAMPAÑAS DE OFERTAS  (Cyber NOVAK)
-- ---------------------------------------------------------------------
create table if not exists public.campanas (
    id            bigint generated by default as identity primary key,
    nombre        text not null,
    subtitulo     text not null default '',
    inicio        timestamptz not null,
    fin           timestamptz not null,
    stock_minimo  int not null default 1 check (stock_minimo >= 0),
    activa        boolean not null default true,      -- la tienda usa la activa más reciente
    creado_en     timestamptz not null default now(),
    check (fin > inicio)
);


-- ---------------------------------------------------------------------
-- 3. PRODUCTOS  (una fila por prenda; el stock NO va aquí, va en variantes)
-- ---------------------------------------------------------------------
create table if not exists public.productos (
    id                text primary key,               -- 'hoodies-08' (el mismo id de hoy)
    sku               text not null unique,           -- 'NVK-HOODIES08'
    nombre            text not null,
    categoria_id      text not null references public.categorias (id),
    genero            text not null default 'hombre' check (genero in ('hombre', 'mujer', 'unisex')),
    descripcion       text not null default '',       -- texto corto de la tarjeta
    detalle           text not null default '',       -- texto largo de la ficha
    precio            numeric(10, 2) not null check (precio >= 0),
    descuento         int  not null default 0 check (descuento between 0 and 99),   -- % de oferta
    -- Si la oferta es de una campaña, sus fechas son las de la campaña;
    -- si es una oferta suelta, termina en oferta_hasta.
    campana_id        bigint references public.campanas (id) on delete set null,
    oferta_hasta      timestamptz,
    imagen            text not null default '',       -- vista frente
    vista_espalda     text not null default '',
    vista_izquierda   text not null default '',
    vista_derecha     text not null default '',
    especificaciones  jsonb not null default '[]'::jsonb,   -- [["Material","Algodón..."], ...]
    nuevo             boolean not null default false,
    activo            boolean not null default true,  -- false = oculto en la tienda (sin borrarlo)
    creado_en         timestamptz not null default now()
);
create index if not exists productos_categoria_idx on public.productos (categoria_id);


-- ---------------------------------------------------------------------
-- 4. VARIANTES  (stock por TALLA y COLOR)
--    Ejemplo: hoodies-08 · M · Terracota · stock 4
-- ---------------------------------------------------------------------
create table if not exists public.variantes (
    id            bigint generated always as identity primary key,
    producto_id   text not null references public.productos (id) on delete cascade,
    talla         text not null,
    color         text not null,
    color_hex     text not null default '#1b1b1f',
    -- "check (stock >= 0)" es el seguro final contra vender de más:
    -- Postgres rechaza cualquier operación que deje el stock en negativo.
    stock         int  not null default 0 check (stock >= 0),
    orden_talla   int  not null default 0,            -- para mostrar XS, S, M... en orden
    orden_color   int  not null default 0,            -- 0 = color principal (el de la foto)
    unique (producto_id, talla, color)
);
create index if not exists variantes_producto_idx on public.variantes (producto_id);


-- ---------------------------------------------------------------------
-- 5. CLIENTES  (perfil de cada cuenta; la contraseña la guarda Supabase Auth,
--    NUNCA en esta tabla). El id es el mismo de auth.users.
-- ---------------------------------------------------------------------
create table if not exists public.clientes (
    id          uuid primary key references auth.users (id) on delete cascade,
    correo      text not null unique,
    nombre      text not null default '',
    rol         text not null default 'usuario' check (rol in ('usuario', 'admin')),
    genero      text not null default '',
    nacimiento  date,
    telefono    text not null default '',
    distrito    text not null default '',
    talla       text not null default '',
    prendas     text[] not null default '{}',         -- categorías favoritas
    estilo      text not null default '',
    newsletter  boolean not null default false,
    creado_en   timestamptz not null default now()
);

-- ¿El usuario que consulta es administrador?
-- "security definer" = se ejecuta con permisos del dueño, así puede leer
-- la tabla clientes sin quedar atrapada en sus propias políticas.
create or replace function public.es_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1 from public.clientes
        where id = auth.uid() and rol = 'admin'
    );
$$;

-- Un cliente puede editar su perfil, pero NO darse rol de admin a sí mismo.
-- (Desde el SQL Editor de Supabase sí se puede: ahí trabajas como dueño.)
create or replace function public.proteger_rol()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    if new.rol is distinct from old.rol
       and current_user in ('anon', 'authenticated')
       and not public.es_admin() then
        raise exception 'Solo un administrador puede cambiar el rol de una cuenta.';
    end if;
    new.id := old.id;   -- el id nunca cambia
    return new;
end;
$$;

drop trigger if exists clientes_proteger_rol on public.clientes;
create trigger clientes_proteger_rol
    before update on public.clientes
    for each row execute function public.proteger_rol();


