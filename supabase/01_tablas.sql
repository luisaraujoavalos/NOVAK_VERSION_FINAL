-- ---------------------------------------------------------------------
-- 7. PEDIDOS
--    Los números siguen el formato de hoy: NV-20000, NV-20001...
--    (empiezan en 20000 para no chocar con los pedidos de ejemplo NV-10240...)
-- ---------------------------------------------------------------------
create sequence if not exists public.pedidos_numero_seq start 20000;

create table if not exists public.pedidos (
    id               text primary key default ('NV-' || nextval('public.pedidos_numero_seq')),
    cliente_id       uuid references public.clientes (id) on delete set null,
    correo           text not null,                   -- copia: el pedido se conserva aunque borren la cuenta
    nombre           text not null,
    telefono         text not null default '',
    dni              text not null default '',
    fecha            timestamptz not null default now(),
    subtotal         numeric(10, 2) not null default 0,
    descuento_cupon  numeric(10, 2) not null default 0,
    cupon_codigo     text not null default '',
    envio            numeric(10, 2) not null default 0,
    total            numeric(10, 2) not null default 0,
    metodo           text not null check (metodo in ('tarjeta', 'yape', 'pagoefectivo', 'transferencia', 'contraentrega')),
    pago_detalle     text not null default '',
    estado           text not null default 'Pendiente de pago'
                     check (estado in ('Pendiente de pago', 'Pagado', 'Preparando', 'En camino', 'Entregado', 'Cancelado')),
    entrega          jsonb not null default '{}'::jsonb,   -- {tipo, direccion, distrito, zona...}
    es_ejemplo       boolean not null default false        -- true = pedido de prueba (DATOS_DE_EJEMPLO)
);
alter sequence public.pedidos_numero_seq owned by public.pedidos.id;
create index if not exists pedidos_cliente_idx on public.pedidos (cliente_id);
create index if not exists pedidos_fecha_idx   on public.pedidos (fecha);


-- ---------------------------------------------------------------------
-- 8. ITEMS DEL PEDIDO  (cada línea: prenda + talla + color + cantidad)
--    Se guarda una copia del nombre y del precio: si mañana cambias el
--    precio de la prenda, el pedido antiguo no cambia.
-- ---------------------------------------------------------------------
create table if not exists public.pedido_items (
    id            bigint generated always as identity primary key,
    pedido_id     text not null references public.pedidos (id) on delete cascade,
    producto_id   text references public.productos (id) on delete set null,
    variante_id   bigint references public.variantes (id) on delete set null,
    nombre        text not null,
    categoria     text not null default '',
    talla         text not null,
    color         text not null,
    cantidad      int  not null check (cantidad > 0),
    precio        numeric(10, 2) not null,            -- precio pagado por unidad
    precio_lista  numeric(10, 2) not null,            -- precio sin oferta
    oferta        boolean not null default false,
    imagen        text not null default ''
);
create index if not exists pedido_items_pedido_idx   on public.pedido_items (pedido_id);
create index if not exists pedido_items_producto_idx on public.pedido_items (producto_id);


-- ---------------------------------------------------------------------
-- 9. RESEÑAS
-- ---------------------------------------------------------------------
create table if not exists public.resenas (
    id           bigint generated always as identity primary key,
    producto_id  text not null references public.productos (id) on delete cascade,
    cliente_id   uuid not null default auth.uid() references public.clientes (id) on delete cascade,
    nombre       text not null default '',            -- 'Camila R.'
    estrellas    int  not null check (estrellas between 1 and 5),
    texto        text not null check (char_length(texto) between 5 and 2000),
    foto_url     text not null default '',
    talla        text not null default '',
    verificada   boolean not null default false,      -- lo calcula la base, no el navegador
    creado_en    timestamptz not null default now()
);
create index if not exists resenas_producto_idx on public.resenas (producto_id);

-- Antes de guardar una reseña, la base decide si es "Compra verificada"
-- revisando los pedidos reales del cliente. Así nadie puede falsificarla.
create or replace function public.preparar_resena()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_item record;
begin
    select i.talla into v_item
    from public.pedidos p
    join public.pedido_items i on i.pedido_id = p.id
    where p.cliente_id = new.cliente_id
      and p.estado <> 'Cancelado'
      and i.producto_id = new.producto_id
    limit 1;

    new.verificada := found;
    new.talla      := coalesce(v_item.talla, '');
    new.creado_en  := now();
    -- Nombre corto: "Camila Rojas" → "Camila R."
    select split_part(c.nombre, ' ', 1) ||
           case when split_part(c.nombre, ' ', 2) <> ''
                then ' ' || left(split_part(c.nombre, ' ', 2), 1) || '.' else '' end
      into new.nombre
    from public.clientes c where c.id = new.cliente_id;
    return new;
end;
$$;

drop trigger if exists resenas_preparar on public.resenas;
create trigger resenas_preparar
    before insert on public.resenas
    for each row execute function public.preparar_resena();


