grant select on public.categorias, public.campanas, public.productos,
                public.variantes, public.cupones, public.resenas
      to anon, authenticated;

grant insert, update, delete on public.categorias, public.campanas, public.productos,
                                public.variantes, public.cupones
      to authenticated;

grant select, update        on public.clientes      to authenticated;
grant select, update        on public.pedidos       to authenticated;
grant select                on public.pedido_items  to authenticated;
grant insert, delete        on public.resenas       to authenticated;
grant select, insert, delete on public.favoritos    to authenticated;

grant insert                on public.eventos_producto to anon, authenticated;
grant select                on public.eventos_producto to authenticated;
grant insert                on public.reclamaciones    to anon, authenticated;
grant select, update        on public.reclamaciones    to authenticated;
grant usage                 on sequence public.reclamaciones_numero_seq to anon, authenticated;

grant execute on function public.es_admin() to anon, authenticated;

